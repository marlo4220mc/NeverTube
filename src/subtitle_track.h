#pragma once

#include <QJsonArray>
#include <QString>
#include <QVector>

struct SubtitleTrack
{
    QString baseUrl;
    QString languageCode;
    QString label;
    bool autoGenerated = false;
    bool translatable = false;
};

struct SubtitleTranslation
{
    QString languageCode;
    QString label;
};

QVector<SubtitleTrack> parseSubtitleTracks(const QJsonArray &tracks);
QVector<SubtitleTranslation> parseSubtitleTranslations(const QJsonArray &languages);
QString subtitleUrl(const SubtitleTrack &track, const QString &targetLanguage = QString());
int preferredSubtitleIndex(const QVector<SubtitleTrack> &tracks,
                           const QString &preferredLanguage);
