#include "subtitle_track.h"
#include "ui/subtitle_overlay.h"
#include <QJsonObject>
#include <cstdio>

namespace {

// Sample VTT exactly as YouTube delivers it: word-timing marks, inline tags
// and explicit newlines inside a cue.
QByteArray youTubeVtt()
{
    return QByteArray(
        "WEBVTT\n"
        "\n"
        "00:00:01.000 --> 00:00:04.000 align:start position:0%\n"
        "<00:00:01.000><c>Hello</c><00:00:01.500><c> world</c><00:00:02.000><c>!</c>\n"
        "<00:00:02.200><c>Second line</c>\n"
        "\n"
        "00:00:04.500 --> 00:00:06.000\n"
        "just <b>plain</b> text\n");
}

}  // namespace

bool subtitleTrackSelfTest()
{
    bool ok = true;
    auto check = [&ok](bool v, const char *s) {
        std::printf("  SUBTITLE %s: %s\n", v ? "OK" : "FAIL", s);
        ok = ok && v;
    };

    // ── Caption tracks (player response) ────────────────────────────────
    QJsonArray tracks;
    tracks.append(QJsonObject{{"baseUrl", "https://x.test/timedtext?v=1"}, {"languageCode", "en"}, {"name", QJsonObject{{"simpleText", "English"}}}});
    tracks.append(QJsonObject{{"baseUrl", "https://x.test/timedtext?v=2"}, {"languageCode", "es"}, {"name", QJsonObject{{"simpleText", "Español"}}}, {"kind", "asr"}});
    const auto parsed = parseSubtitleTracks(tracks);
    check(parsed.size() == 2, "parsea las pistas");
    check(parsed.size() == 2 && parsed.at(1).autoGenerated, "detecta ASR");
    check(preferredSubtitleIndex(parsed, "es") == 1, "prefiere idioma solicitado");
    check(preferredSubtitleIndex(parsed, "fr") == 0, "hace fallback a la primera pista");
    check(subtitleUrl(parsed.at(0), "es").contains("fmt=vtt"), "solicita WebVTT");
    check(subtitleUrl(parsed.at(0), "es").contains("tlang=es"), "añade traducción");

    // ── WebVTT parser (the Qt overlay's pure part) ──────────────────────
    const auto cues = vtt::parse(youTubeVtt());
    check(cues.size() == 2, "vtt: parsea los cues");
    if (cues.size() == 2) {
        const vtt::Cue &first = cues.at(0);
        check(first.startMs == 1000.0 && first.endMs == 4000.0,
              "vtt: tiempos intactos (saltos no truncados)");
        check(first.text == QLatin1String("Hello world! Second line"),
              "vtt: quita marcas de palabra y une las líneas con espacio");
        const vtt::Cue &second = cues.at(1);
        check(second.text == QLatin1String("just plain text"),
              "vtt: quita los tags inline (<b>)");
    }
    // Explicit jump inside a cue: the whole cue stays active across the gap.
    check(vtt::cueAt(cues, 1000.0) == 0, "vtt: cue activo en su inicio");
    check(vtt::cueAt(cues, 4000.0) == -1, "vtt: cue termina en endMs (sin solapamiento)");
    check(vtt::cueAt(cues, 5000.0) == 1, "vtt: siguiente cue activo");
    check(vtt::cueAt(cues, 0.0) == -1, "vtt: antes del primer cue no hay nada");

    // A "MM:SS.mmm" timing (no hour field) and an empty payload.
    const auto shortTiming = vtt::parse(
        QByteArray("WEBVTT\n\n1:23.456 --> 1:25.000\n<00:01:23.700><c>X</c>\n"));
    check(shortTiming.size() == 1
          && shortTiming.at(0).startMs == 83456.0,
          "vtt: acepta M:SS.mmm");
    check(vtt::parse(QByteArray("WEBVTT\n\n")).isEmpty(),
          "vtt: payload vacío no produce cues");
    return ok;
}
