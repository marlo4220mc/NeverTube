#include "subtitle_track.h"

#include <QJsonObject>
#include <QJsonValue>
#include <QUrl>
#include <QUrlQuery>

namespace {
QString textValue(const QJsonObject &object, const QString &key)
{
    const QJsonObject value = object.value(key).toObject();
    const QString simple = value.value(QStringLiteral("simpleText")).toString();
    if (!simple.isEmpty())
        return simple;
    QString result;
    const QJsonArray runs = value.value(QStringLiteral("runs")).toArray();
    for (const QJsonValue &run : runs)
        result += run.toObject().value(QStringLiteral("text")).toString();
    return result;
}
}

QVector<SubtitleTrack> parseSubtitleTracks(const QJsonArray &tracks)
{
    QVector<SubtitleTrack> result;
    for (const QJsonValue &value : tracks) {
        const QJsonObject object = value.toObject();
        SubtitleTrack track;
        track.baseUrl = object.value(QStringLiteral("baseUrl")).toString();
        track.languageCode = object.value(QStringLiteral("languageCode")).toString();
        track.label = textValue(object, QStringLiteral("name"));
        track.autoGenerated = object.value(QStringLiteral("kind")).toString()
                              == QLatin1String("asr");
        // YouTube marks translatable tracks with "isTranslatable" (usually the
        // auto-generated ones). Accept the bare "translatable" variant too, so
        // a client that renames the field does not silently disable
        // translation for every video.
        track.translatable = object.value(QStringLiteral("isTranslatable")).toBool()
                             || object.value(QStringLiteral("translatable")).toBool();
        if (!track.baseUrl.isEmpty() && !track.languageCode.isEmpty())
            result.append(track);
    }
    return result;
}

QVector<SubtitleTranslation> parseSubtitleTranslations(const QJsonArray &languages)
{
    QVector<SubtitleTranslation> result;
    for (const QJsonValue &value : languages) {
        const QJsonObject object = value.toObject();
        SubtitleTranslation translation;
        translation.languageCode = object.value(QStringLiteral("languageCode")).toString();
        translation.label = textValue(object, QStringLiteral("languageName"));
        if (!translation.languageCode.isEmpty())
            result.append(translation);
    }
    return result;
}

QString subtitleUrl(const SubtitleTrack &track, const QString &targetLanguage)
{
    QUrl url(track.baseUrl);
    QUrlQuery query(url);
    if (!query.hasQueryItem(QStringLiteral("fmt")))
        query.addQueryItem(QStringLiteral("fmt"), QStringLiteral("vtt"));
    if (!targetLanguage.isEmpty())
        query.addQueryItem(QStringLiteral("tlang"), targetLanguage);
    url.setQuery(query);
    return url.toString(QUrl::FullyEncoded);
}

int preferredSubtitleIndex(const QVector<SubtitleTrack> &tracks,
                           const QString &preferredLanguage)
{
    if (tracks.isEmpty())
        return -1;
    for (int pass = 0; pass < 2; ++pass) {
        for (int i = 0; i < tracks.size(); ++i) {
            const SubtitleTrack &track = tracks.at(i);
            const bool languageMatches = preferredLanguage.isEmpty()
                || track.languageCode == preferredLanguage
                || track.languageCode.startsWith(preferredLanguage + QLatin1Char('-'));
            if (languageMatches && (pass == 1 || !track.autoGenerated))
                return i;
        }
    }
    return 0;
}

SubtitlePick pickSubtitleSource(const QVector<SubtitleTrack> &tracks,
                                const QString &preferredLanguage,
                                bool autoTranslate,
                                const QString &interfaceLanguage)
{
    SubtitlePick out;
    if (tracks.isEmpty())
        return out;

    // "original" (empty preferred) -> prefer a manual track, any language.
    const int native = preferredSubtitleIndex(tracks, preferredLanguage);
    if (native < 0)
        return out;

    // Translation target: the preferred language, or the interface language
    // when "original" is combined with auto-translate.
    QString target;
    if (!preferredLanguage.isEmpty()) {
        target = preferredLanguage;
    } else if (autoTranslate) {
        target = interfaceLanguage;
    }

    const SubtitleTrack &nativeTrack = tracks.at(native);
    const bool nativeInTarget = !target.isEmpty()
        && (nativeTrack.languageCode == target
            || nativeTrack.languageCode.startsWith(target + QLatin1Char('-')));

    // No translation wanted, or the native track is already in the target
    // language: load it as-is (no tlang).
    if (!autoTranslate || target.isEmpty() || nativeInTarget) {
        out.index = native;
        return out;
    }

    // Auto-translation: the source must be translatable. Prefer one in the
    // same language as the native pick (keeps the original language), then
    // any translatable track (usually the original ASR).
    for (int i = 0; i < tracks.size(); ++i) {
        const SubtitleTrack &t = tracks.at(i);
        if (t.translatable && t.languageCode == nativeTrack.languageCode) {
            out.index = i;
            out.target = target;
            return out;
        }
    }
    for (int i = 0; i < tracks.size(); ++i) {
        if (tracks.at(i).translatable) {
            out.index = i;
            out.target = target;
            return out;
        }
    }
    // No translatable track: load the native pick untranslated rather than
    // failing (a tlang on a non-translatable track is silently ignored).
    out.index = native;
    return out;
}
