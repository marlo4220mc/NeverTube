#include "subtitle_track.h"

#include <QJsonObject>
#include <QJsonValue>
#include <QUrl>
#include <QUrlQuery>

namespace {
QString textValue(const QJsonObject &object, const QString &key)
{
    const QJsonObject value = object.value(key).toObject();
    const QString simple = value.value(QStringLiteral("simpleText")).toString();
    if (!simple.isEmpty())
        return simple;
    QString result;
    const QJsonArray runs = value.value(QStringLiteral("runs")).toArray();
    for (const QJsonValue &run : runs)
        result += run.toObject().value(QStringLiteral("text")).toString();
    return result;
}
}

QVector<SubtitleTrack> parseSubtitleTracks(const QJsonArray &tracks)
{
    QVector<SubtitleTrack> result;
    for (const QJsonValue &value : tracks) {
        const QJsonObject object = value.toObject();
        SubtitleTrack track;
        track.baseUrl = object.value(QStringLiteral("baseUrl")).toString();
        track.languageCode = object.value(QStringLiteral("languageCode")).toString();
        track.label = textValue(object, QStringLiteral("name"));
        track.autoGenerated = object.value(QStringLiteral("kind")).toString()
                              == QLatin1String("asr");
        track.translatable = object.value(QStringLiteral("isTranslatable")).toBool();
        if (!track.baseUrl.isEmpty() && !track.languageCode.isEmpty())
            result.append(track);
    }
    return result;
}

QVector<SubtitleTranslation> parseSubtitleTranslations(const QJsonArray &languages)
{
    QVector<SubtitleTranslation> result;
    for (const QJsonValue &value : languages) {
        const QJsonObject object = value.toObject();
        SubtitleTranslation translation;
        translation.languageCode = object.value(QStringLiteral("languageCode")).toString();
        translation.label = textValue(object, QStringLiteral("languageName"));
        if (!translation.languageCode.isEmpty())
            result.append(translation);
    }
    return result;
}

QString subtitleUrl(const SubtitleTrack &track, const QString &targetLanguage)
{
    QUrl url(track.baseUrl);
    QUrlQuery query(url);
    if (!query.hasQueryItem(QStringLiteral("fmt")))
        query.addQueryItem(QStringLiteral("fmt"), QStringLiteral("vtt"));
    if (!targetLanguage.isEmpty())
        query.addQueryItem(QStringLiteral("tlang"), targetLanguage);
    url.setQuery(query);
    return url.toString(QUrl::FullyEncoded);
}

int preferredSubtitleIndex(const QVector<SubtitleTrack> &tracks,
                           const QString &preferredLanguage)
{
    if (tracks.isEmpty())
        return -1;
    for (int pass = 0; pass < 2; ++pass) {
        for (int i = 0; i < tracks.size(); ++i) {
            const SubtitleTrack &track = tracks.at(i);
            const bool languageMatches = preferredLanguage.isEmpty()
                || track.languageCode == preferredLanguage
                || track.languageCode.startsWith(preferredLanguage + QLatin1Char('-'));
            if (languageMatches && (pass == 1 || !track.autoGenerated))
                return i;
        }
    }
    return 0;
}
